CREATE TABLE pets (
    id UUID PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    species VARCHAR(80) NOT NULL,
    hunger INTEGER NOT NULL DEFAULT 50,
    happiness INTEGER NOT NULL DEFAULT 50,
    health INTEGER NOT NULL DEFAULT 100,
    status VARCHAR(24) NOT NULL DEFAULT 'HEALTHY',
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_pets_hunger CHECK (hunger BETWEEN 0 AND 100),
    CONSTRAINT chk_pets_happiness CHECK (happiness BETWEEN 0 AND 100),
    CONSTRAINT chk_pets_health CHECK (health BETWEEN 0 AND 100),
    CONSTRAINT chk_pets_status CHECK (status IN ('HEALTHY', 'SLEEPING', 'SICK'))
);
